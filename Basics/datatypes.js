
// Data Types in JavaScript
// JavaScript has data types similar to other programming languages like Python.

// String
let Name = "Saurav";

// Number
let age = 18;

// Boolean
let IsLoggedIn = true;

// Null
let data = null;


// Checking the data type using typeof

console.log(typeof "Saurav");   // string
console.log(typeof 18);         // number
console.log(typeof true);       // boolean
console.log(typeof undefined);  // undefined

// Note:
// typeof null returns "object".
// This is a historical behavior/quirk of JavaScript.
// Although null is a primitive data type, typeof null gives "object".

console.log(typeof data);       // object , Null means Empty

